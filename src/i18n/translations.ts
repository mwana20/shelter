/**
 * Universal translation getter:
 * Supports getTranslation(lang, key) or getTranslation(key, lang)
 * Defaults to 'en' fallback if missing or key not found.
 */
export function getTranslation(param1: string, param2?: string): string {
  const isFirstParamLang = Boolean(translations[param1]);
  const lang = isFirstParamLang ? param1 : (param2 || 'en');
  const key = isFirstParamLang ? (param2 || '') : param1;

  if (translations[lang] && translations[lang][key]) {
    return translations[lang][key];
  }

  // Fallback to English
  if (translations.en && translations.en[key]) {
    return translations.en[key];
  }

  // Return the raw key if no translation found
  return key;
}
